    delete from public.troll_shields where user_id = p_user;
  end if;
  perform public.write_audit(case when p_on then 'troll_shield_on' else 'troll_shield_off' end, p_user,
    jsonb_build_object('raison', nullif(btrim(p_reason), '')));
end;
$$;

